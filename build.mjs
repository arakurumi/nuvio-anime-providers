import { build, context } from "esbuild";

const watch = process.argv.includes("--watch");

const providers = [
	{ globalName: "HianimeProvider", name: "hianime" },
	{ globalName: "OtakudesuProvider", name: "otakudesu" },
	{ globalName: "OploverzProvider", name: "oploverz" },
	{ globalName: "AnoboyProvider", name: "anoboy" },
	{ globalName: "AnichinProvider", name: "anichin" },
	{ globalName: "GomunimeProvider", name: "gomunime" },
	{ globalName: "GogoanimesProvider", name: "gogoanimes" },
];

for (const provider of providers) {
	const options = {
		banner: {
			js: `/* ${provider.name} provider for Nuvio - generated by build.mjs, do not edit here. */`,
		},
		bundle: true,
		charset: "utf8",
		entryPoints: [`src/${provider.name}/index.js`],
		footer: {
			js: [
				";(function (provider) {",
				'  if (typeof module !== "undefined" && module && module.exports) module.exports.getStreams = provider.getStreams;',
				'  if (typeof globalThis !== "undefined") globalThis.getStreams = provider.getStreams;',
				`})(${provider.globalName});`,
			].join("\n"),
		},
		format: "iife",
		globalName: provider.globalName,
		legalComments: "none",
		outfile: `providers/${provider.name}.js`,
		platform: "neutral",
		target: ["es2020"],
	};

	if (watch) {
		const builder = await context(options);
		await builder.watch();
		console.log(
			`Watching src/${provider.name} -> providers/${provider.name}.js`,
		);
	} else {
		await build(options);
		console.log(`Built providers/${provider.name}.js`);
	}
}
