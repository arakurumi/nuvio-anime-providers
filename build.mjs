import { build, context } from 'esbuild';
import { readFile } from 'node:fs/promises';

const watch = process.argv.includes('--watch');

const providers = [
  { name: 'hianime', globalName: 'HianimeProvider' },
  { name: 'otakudesu', globalName: 'OtakudesuProvider' },
  { name: 'oploverz', globalName: 'OploverzProvider' },
  { name: 'anoboy', globalName: 'AnoboyProvider' },
  { name: 'anichin', globalName: 'AnichinProvider' },
  { name: 'gomunime', globalName: 'GomunimeProvider' },
  { name: 'gogoanimes', globalName: 'GogoanimesProvider' },
];

for (const provider of providers) {
  const options = {
    entryPoints: [`src/${provider.name}/index.js`],
    outfile: `providers/${provider.name}.js`,
    bundle: true,
    format: 'iife',
    globalName: provider.globalName,
    platform: 'neutral',
    target: ['es2020'],
    charset: 'utf8',
    legalComments: 'none',
    banner: {
      js: `/* ${provider.name} provider for Nuvio - generated by build.mjs, do not edit here. */`,
    },
    footer: {
      js: [
        ';(function (provider) {',
        '  if (typeof module !== "undefined" && module && module.exports) module.exports.getStreams = provider.getStreams;',
        '  if (typeof globalThis !== "undefined") globalThis.getStreams = provider.getStreams;',
        `})(${provider.globalName});`,
      ].join('\n'),
    },
  };

  if (watch) {
    const builder = await context(options);
    await builder.watch();
    console.log(`Watching src/${provider.name} -> providers/${provider.name}.js`);
  } else {
    await build(options);
    console.log(`Built providers/${provider.name}.js`);
  }
}
